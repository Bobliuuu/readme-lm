#!/usr/bin/env python3
"""build_profile.py OUT_DIR --owner NAME [--repo readme-lm] : populate a profile repo checkout from profile-template/.

New files are copied (never overwritten). README.md: if OUT_DIR/README.md is missing it is created from the
template; if it exists only the model block (between LM-WEIGHTS markers) and the demo section (between LM-DEMO
markers) are added or refreshed, nothing else is touched. The model block comes from qa/weights.md.
assets/readme-lm.svg is regenerated by running ask.py against the final README (this is also the self-test).
"""
import argparse, base64, hashlib, io, os, re, shutil, subprocess, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); TPL = os.path.join(ROOT, "profile-template")
ap = argparse.ArgumentParser(); ap.add_argument("out"); ap.add_argument("--owner", required=True)
ap.add_argument("--repo", default="readme-lm"); a = ap.parse_args()
if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,38}", a.owner) or not re.fullmatch(r"[A-Za-z0-9._-]{1,100}", a.repo):
    sys.exit("bad owner/repo name")
out = a.out; os.makedirs(out, exist_ok=True)
sub = lambda t: t.replace("OWNER", a.owner).replace("REPO", a.repo)

# 1. the model block, exactly the shape export_qa.py writes and qa_infer.py reads
w = open(os.path.join(ROOT, "qa", "weights.md")).read()
b64 = re.search(r"```\n(.*?)\n```", w, re.S).group(1).replace("\n", "")
Z = np.load(io.BytesIO(base64.b64decode(b64)))
params = sum(Z[k].size for k in Z.files if k.endswith("_q")) * 2
lines = "\n".join(b64[i:i + 120] for i in range(0, len(b64), 120))
block = ("<!--LM-WEIGHTS-START-->\n<details><summary>The model: %d-parameter transformer, 4-bit weights, %d KB (this README <b>is</b> the model)</summary>\n\n```\n%s\n```\n\n</details>\n<!--LM-WEIGHTS-END-->"
         % (params, len(b64) // 1024, lines))

# 2. copy template files without overwriting
for dp, ds, fs in os.walk(TPL):
    ds[:] = [d for d in ds if d != "__pycache__"]
    for f in fs:
        src = os.path.join(dp, f); rel = os.path.relpath(src, TPL)
        if rel in ("README.md", "assets/readme-lm.svg"): continue
        dst = os.path.join(out, rel)
        if os.path.exists(dst): print("keep existing", rel); continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if rel.startswith("readme-lm/"): shutil.copyfile(os.path.join(ROOT, os.path.basename(rel)), dst)  # always the current engine
        elif f.endswith(".yml"): open(dst, "w").write(sub(open(src).read()))
        else: shutil.copyfile(src, dst)
        print("wrote", rel)

# 3. README
tpl = sub(open(os.path.join(TPL, "README.md")).read()); rp = os.path.join(out, "README.md")
demo = re.search(r"<!--LM-DEMO-START-->.*?<!--LM-DEMO-END-->", tpl, re.S).group(0)
if not os.path.exists(rp):
    r = re.sub(r"<!--LM-WEIGHTS-START-->.*<!--LM-WEIGHTS-END-->", lambda m: block, tpl, flags=re.S); print("wrote README.md (new)")
else:
    r = open(rp).read()
    r = (re.sub(r"<!--LM-WEIGHTS-START-->.*<!--LM-WEIGHTS-END-->", lambda m: block, r, flags=re.S) if "<!--LM-WEIGHTS-START-->" in r else r.rstrip() + "\n\n" + block + "\n")
    r = (re.sub(r"<!--LM-DEMO-START-->.*?<!--LM-DEMO-END-->", lambda m: demo, r, flags=re.S) if "<!--LM-DEMO-START-->" in r else r.rstrip() + "\n\n" + demo + "\n")
    print("injected model block + demo section into existing README.md")
os.makedirs(os.path.join(out, "assets"), exist_ok=True); svg = os.path.join(out, "assets", "readme-lm.svg")
open(rp, "w").write(r)

# 4. initial animation (also verifies README + ask.py agree), then pin its hash
ans = subprocess.run([sys.executable, "-B", os.path.join(out, "readme-lm", "ask.py"), rp, svg, "0", "what is qwentpu"], capture_output=True, text=True, check=True).stdout.strip()
h = hashlib.sha1(open(svg, "rb").read()).hexdigest()[:8]
r = re.sub(r"assets/readme-lm\.svg(\?v=[0-9a-f]+)?", "assets/readme-lm.svg?v=" + h, r); open(rp, "w").write(r)
print("README size: %d bytes (GitHub renders up to 500 KiB)" % len(r.encode())); print("self-test answer:", ans[:80])
if len(r.encode()) > 500 * 1024: sys.exit("README exceeds 500 KiB")
